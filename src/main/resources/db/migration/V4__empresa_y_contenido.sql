-- V4: empresa, contenido del sitio, medios y ediciones de la Home

-- Datos de contacto de la empresa.
--
-- Es un registro unico. La forma correcta de garantizarlo en Oracle es una
-- columna constante con indice unico: la columna vale siempre 1, y el indice
-- impide que existan dos filas. No se usa un CHECK sobre el ID porque, al
-- borrar la fila, el siguiente ID generado seria 2 y el CHECK lo rechazaria.
CREATE TABLE EMPRESA (
    ID                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    SINGULAR            NUMBER(1) DEFAULT 1 NOT NULL,
    NOMBRE              VARCHAR2(80) NOT NULL,
    SLOGAN              VARCHAR2(150),
    DESCRIPCION         VARCHAR2(600),
    WHATSAPP            VARCHAR2(20) NOT NULL,
    TELEFONO            VARCHAR2(20),
    EMAIL               VARCHAR2(120),
    DIRECCION           VARCHAR2(200),
    CIUDAD              VARCHAR2(80),
    PAIS                VARCHAR2(80),
    INSTAGRAM           VARCHAR2(120),
    TIKTOK              VARCHAR2(120),
    FACEBOOK            VARCHAR2(120),
    YOUTUBE             VARCHAR2(120),
    HORARIO             VARCHAR2(150),
    FECHA_CREACION      TIMESTAMP(6) NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_EMPRESA PRIMARY KEY (ID),
    CONSTRAINT CK_EMPRESA_SINGULAR CHECK (SINGULAR = 1),
    CONSTRAINT CK_EMPRESA_WHATSAPP CHECK (LENGTH(WHATSAPP) BETWEEN 7 AND 20)
);

-- Secciones del sitio: hero, quienes somos, ediciones, movimiento y contacto.
-- La clave identifica la seccion en el codigo; el contenido es editable.
CREATE TABLE SECCION_SITIO (
    ID                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CLAVE               VARCHAR2(40) NOT NULL,
    EYEBROW             VARCHAR2(80),
    TITULO              VARCHAR2(200),
    CUERPO              VARCHAR2(2000),
    ORDEN               NUMBER(5) NOT NULL,
    ACTIVA              BOOLEAN DEFAULT TRUE NOT NULL,
    FECHA_CREACION      TIMESTAMP(6) NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_SECCION_SITIO PRIMARY KEY (ID),
    CONSTRAINT UK_SECCION_SITIO_CLAVE UNIQUE (CLAVE),
    CONSTRAINT CK_SECCION_SITIO_ORDEN CHECK (ORDEN >= 0)
);

-- Logo e imagenes de las secciones. SECCION_ID puede quedar nulo cuando el
-- medio no pertenece a una seccion concreta (por ejemplo el logo general).
CREATE TABLE MEDIA_SITIO (
    ID                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    SECCION_ID          NUMBER,
    TIPO                VARCHAR2(20) NOT NULL,
    URL                 VARCHAR2(500) NOT NULL,
    PUBLIC_ID           VARCHAR2(200) NOT NULL,
    ALT                 VARCHAR2(200),
    ANCHO               NUMBER(6),
    ALTO                NUMBER(6),
    ORDEN               NUMBER(5) NOT NULL,
    ACTIVA              BOOLEAN DEFAULT TRUE NOT NULL,
    FECHA_CREACION      TIMESTAMP(6) NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_MEDIA_SITIO PRIMARY KEY (ID),
    CONSTRAINT FK_MEDIA_SITIO_SECCION FOREIGN KEY (SECCION_ID) REFERENCES SECCION_SITIO (ID),
    CONSTRAINT CK_MEDIA_SITIO_TIPO CHECK (TIPO IN ('LOGO', 'IMAGEN')),
    CONSTRAINT CK_MEDIA_SITIO_ORDEN CHECK (ORDEN >= 0)
);

-- Videos del sitio (seccion "En movimiento"). POSTER_URL es la imagen del
-- primer frame que se muestra mientras el video carga.
CREATE TABLE VIDEO_SITIO (
    ID                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    SECCION_ID          NUMBER,
    TITULO              VARCHAR2(120) NOT NULL,
    ETIQUETA            VARCHAR2(120),
    URL                 VARCHAR2(500) NOT NULL,
    PUBLIC_ID           VARCHAR2(200) NOT NULL,
    POSTER_URL          VARCHAR2(500),
    ANCHO               NUMBER(6),
    ALTO                NUMBER(6),
    DURACION_SEG        NUMBER(6),
    ORDEN               NUMBER(5) NOT NULL,
    ACTIVA              BOOLEAN DEFAULT TRUE NOT NULL,
    FECHA_CREACION      TIMESTAMP(6) NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_VIDEO_SITIO PRIMARY KEY (ID),
    CONSTRAINT FK_VIDEO_SITIO_SECCION FOREIGN KEY (SECCION_ID) REFERENCES SECCION_SITIO (ID),
    CONSTRAINT CK_VIDEO_SITIO_ORDEN CHECK (ORDEN >= 0)
);

-- Ediciones de la Home: la curaduría que el admin decide mostrar.
-- No duplica el producto: precio, tallas, stock e imagenes salen de PRODUCTO.
-- La seccion "Home" solo muestra las ediciones activas cuyo producto esta
-- en estado PUBLICADO.
CREATE TABLE EDICION (
    ID                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    PRODUCTO_ID         NUMBER NOT NULL,
    EYEBROW             VARCHAR2(60),
    TITULO              VARCHAR2(120),
    DESCRIPCION         VARCHAR2(600),
    ORDEN               NUMBER(5) NOT NULL,
    ACTIVA              BOOLEAN DEFAULT TRUE NOT NULL,
    FECHA_CREACION      TIMESTAMP(6) NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_EDICION PRIMARY KEY (ID),
    CONSTRAINT FK_EDICION_PRODUCTO FOREIGN KEY (PRODUCTO_ID) REFERENCES PRODUCTO (ID),
    CONSTRAINT CK_EDICION_ORDEN CHECK (ORDEN >= 0)
);

CREATE INDEX IDX_MEDIA_SITIO_SECCION ON MEDIA_SITIO (SECCION_ID);
CREATE INDEX IDX_VIDEO_SITIO_SECCION ON VIDEO_SITIO (SECCION_ID);
CREATE INDEX IDX_EDICION_PRODUCTO ON EDICION (PRODUCTO_ID);

-- Solo puede existir una empresa: el indice unico sobre la columna constante.
CREATE UNIQUE INDEX UK_EMPRESA_UNICA ON EMPRESA (SINGULAR);

