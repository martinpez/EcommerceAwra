-- V3: imagenes de producto almacenadas en Cloudinary

CREATE TABLE IMAGEN_PRODUCTO (
    ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    PRODUCTO_ID   NUMBER NOT NULL,
    URL           VARCHAR2(500) NOT NULL,
    PUBLIC_ID     VARCHAR2(200) NOT NULL,
    ORDEN         NUMBER(5) NOT NULL,
    ES_PRINCIPAL  BOOLEAN DEFAULT FALSE NOT NULL,
    FECHA_BAJA    TIMESTAMP(6),
    CONSTRAINT PK_IMAGEN_PRODUCTO PRIMARY KEY (ID),
    CONSTRAINT FK_IMAGEN_PRODUCTO FOREIGN KEY (PRODUCTO_ID) REFERENCES PRODUCTO (ID),
    CONSTRAINT CK_IMAGEN_ORDEN CHECK (ORDEN >= 1)
);

CREATE INDEX IDX_IMAGEN_PRODUCTO ON IMAGEN_PRODUCTO (PRODUCTO_ID);

-- Una sola imagen principal activa por producto.
CREATE UNIQUE INDEX UK_IMAGEN_PRINCIPAL_ACTIVA ON IMAGEN_PRODUCTO (CASE WHEN ES_PRINCIPAL = TRUE AND FECHA_BAJA IS NULL THEN PRODUCTO_ID END);
