-- V1: esquema inicial del backend de inventario y catalogo (Oracle)

CREATE TABLE CATEGORIA (
    ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE      VARCHAR2(100) NOT NULL,
    FECHA_BAJA  TIMESTAMP(6),
    CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID)
);

CREATE TABLE PRODUCTO (
    ID                   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE               VARCHAR2(150) NOT NULL,
    DESCRIPCION          VARCHAR2(1000),
    PRECIO               NUMBER(12,2) NOT NULL,
    CATEGORIA_ID         NUMBER NOT NULL,
    ESTADO_PUBLICACION   VARCHAR2(20) NOT NULL,
    FECHA_CREACION       TIMESTAMP(6) NOT NULL,
    FECHA_ACTUALIZACION  TIMESTAMP(6) NOT NULL,
    FECHA_BAJA           TIMESTAMP(6),
    VERSION              NUMBER(19) NOT NULL,
    CONSTRAINT PK_PRODUCTO PRIMARY KEY (ID),
    CONSTRAINT FK_PRODUCTO_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIA (ID),
    CONSTRAINT CK_PRODUCTO_PRECIO CHECK (PRECIO > 0),
    CONSTRAINT CK_PRODUCTO_ESTADO CHECK (ESTADO_PUBLICACION IN ('BORRADOR', 'PUBLICADO', 'OCULTO', 'ELIMINADO'))
);

CREATE TABLE VARIANTE (
    ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    PRODUCTO_ID   NUMBER NOT NULL,
    TALLA         VARCHAR2(20) NOT NULL,
    COLOR         VARCHAR2(40) NOT NULL,
    SKU           VARCHAR2(50) NOT NULL,
    STOCK         NUMBER(10) DEFAULT 0 NOT NULL,
    STOCK_MINIMO  NUMBER(10) DEFAULT 0 NOT NULL,
    FECHA_BAJA    TIMESTAMP(6),
    VERSION       NUMBER(19) NOT NULL,
    CONSTRAINT PK_VARIANTE PRIMARY KEY (ID),
    CONSTRAINT FK_VARIANTE_PRODUCTO FOREIGN KEY (PRODUCTO_ID) REFERENCES PRODUCTO (ID),
    CONSTRAINT CK_VARIANTE_STOCK CHECK (STOCK >= 0),
    CONSTRAINT CK_VARIANTE_STOCK_MINIMO CHECK (STOCK_MINIMO >= 0)
);

CREATE TABLE MOVIMIENTO_INVENTARIO (
    ID                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    VARIANTE_ID       NUMBER NOT NULL,
    TIPO              VARCHAR2(20) NOT NULL,
    CANTIDAD          NUMBER(10) NOT NULL,
    STOCK_RESULTANTE  NUMBER(10) NOT NULL,
    MOTIVO            VARCHAR2(255),
    FECHA_MOVIMIENTO  TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_MOVIMIENTO_INVENTARIO PRIMARY KEY (ID),
    CONSTRAINT FK_MOVIMIENTO_VARIANTE FOREIGN KEY (VARIANTE_ID) REFERENCES VARIANTE (ID),
    CONSTRAINT CK_MOVIMIENTO_TIPO CHECK (TIPO IN ('ENTRADA', 'VENTA', 'AJUSTE')),
    CONSTRAINT CK_MOVIMIENTO_CANTIDAD CHECK (CANTIDAD <> 0),
    CONSTRAINT CK_MOVIMIENTO_STOCK_RES CHECK (STOCK_RESULTANTE >= 0)
);

CREATE TABLE ALERTA_STOCK (
    ID                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    VARIANTE_ID        NUMBER NOT NULL,
    TIPO               VARCHAR2(20) NOT NULL,
    STOCK_AL_MOMENTO   NUMBER(10) NOT NULL,
    LEIDA              BOOLEAN DEFAULT FALSE NOT NULL,
    FECHA_CREACION     TIMESTAMP(6) NOT NULL,
    FECHA_RESOLUCION   TIMESTAMP(6),
    CONSTRAINT PK_ALERTA_STOCK PRIMARY KEY (ID),
    CONSTRAINT FK_ALERTA_VARIANTE FOREIGN KEY (VARIANTE_ID) REFERENCES VARIANTE (ID),
    CONSTRAINT CK_ALERTA_TIPO CHECK (TIPO IN ('STOCK_BAJO', 'AGOTADO'))
);

CREATE INDEX IDX_PRODUCTO_CATEGORIA ON PRODUCTO (CATEGORIA_ID);
CREATE INDEX IDX_VARIANTE_PRODUCTO ON VARIANTE (PRODUCTO_ID);
CREATE INDEX IDX_MOVIMIENTO_VARIANTE_FECHA ON MOVIMIENTO_INVENTARIO (VARIANTE_ID, FECHA_MOVIMIENTO);
CREATE INDEX IDX_ALERTA_VARIANTE ON ALERTA_STOCK (VARIANTE_ID);

-- Unicidad solo entre registros activos: las filas eliminadas dan NULL y Oracle no indexa los NULL.
CREATE UNIQUE INDEX UK_CATEGORIA_NOMBRE_ACTIVO ON CATEGORIA (CASE WHEN FECHA_BAJA IS NULL THEN NOMBRE END);
CREATE UNIQUE INDEX UK_VARIANTE_SKU_ACTIVO ON VARIANTE (CASE WHEN FECHA_BAJA IS NULL THEN SKU END);

-- Una sola alerta activa (sin resolver) por variante.
CREATE UNIQUE INDEX UK_ALERTA_ACTIVA_VARIANTE ON ALERTA_STOCK (CASE WHEN FECHA_RESOLUCION IS NULL THEN VARIANTE_ID END);
